// The pathname is the only language preference. Russian stays the default.
const BASE = '/tsvetochnyy-ugolok-site';
const stripBase = path => path === BASE ? '/' : path.startsWith(BASE + '/') ? path.slice(BASE.length) : path;
export const getLanguage = (pathname = '/') => /^\/uz(?:\/|$)/.test(stripBase(pathname)) ? 'uz' : 'ru';
export const language = getLanguage(typeof location === 'undefined' ? '/' : location.pathname);

export function languagePath(path, target = language) {
  const url = new URL(path, 'https://local.invalid');
  const base = stripBase(url.pathname).replace(/^\/uz(?=\/|$)/, '') || '/';
  return BASE + (target === 'uz' ? `/uz${base}` : base) + url.search + url.hash;
}

export function t(value, target = language) {
  if (target !== 'uz') return value;
  const key = value.trim();
  let translated = translations[key];
  if (translated === undefined && /^\d+ вариант(?:а|ов)?$/.test(key)) translated = `${key.split(' ')[0]} ta variant`;
  if (translated === undefined && key.startsWith('Подробнее: ')) translated = `Batafsil: ${t(key.slice(11), target)}`;
  const photoSuffix = ' — фотография растения из материалов магазина';
  if (translated === undefined && key.endsWith(photoSuffix)) translated = `${t(key.slice(0, -photoSuffix.length), target)} — do‘kon materiallaridagi haqiqiy o‘simlik surati`;
  return translated === undefined ? value : value.replace(key, translated);
}

// Translate controlled UI text only. Input values and bilingual Telegram drafts
// stay untouched, so customer notes and the original enquiry are never rewritten.
export function localize(root = document) {
  if (language === 'uz') {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (!node.parentElement?.closest('script,style,noscript,textarea,#gift-message')) node.textContent = t(node.textContent);
    }
    const elements = [...(root.nodeType === 1 ? [root] : []), ...root.querySelectorAll('[aria-label],[placeholder],[alt]')];
    for (const element of elements) {
      if (element.matches('[data-language]')) continue;
      for (const attribute of ['aria-label', 'placeholder', 'alt']) {
        if (element.hasAttribute(attribute)) element.setAttribute(attribute, t(element.getAttribute(attribute)));
      }
    }
  }
  for (const link of root.querySelectorAll('a[href^="/"]:not([data-language])')) {
    const href = link.getAttribute('href');
    if (!href.startsWith('//')) link.setAttribute('href', languagePath(href));
  }
}

export function languageSwitcher() {
  return `<nav class="language-switch" aria-label="${t('Выбор языка')}"><a data-language="ru" href="/" lang="ru" hreflang="ru" aria-label="Русский" ${language === 'ru' ? 'aria-current="true"' : ''}>RU</a><a data-language="uz" href="/uz/" lang="uz" hreflang="uz" aria-label="O‘zbekcha" ${language === 'uz' ? 'aria-current="true"' : ''}>UZ</a></nav>`;
}

export function updateLanguageLinks() {
  for (const link of document.querySelectorAll('[data-language]')) link.setAttribute('href', languagePath(location.pathname + location.search + location.hash, link.dataset.language));
}

const draftKey = 'flower-corner-language-draft';
export function saveLanguageDraft() {
  const form = document.querySelector('#gift-form');
  if (!form) return;
  const values = new FormData(form);
  try {
    sessionStorage.setItem(draftKey, JSON.stringify({recipient: values.get('recipient'), budget: values.get('budget'), note: values.get('note'), preview: !document.querySelector('#gift-preview').hidden}));
  } catch { /* Form still works when browser storage is unavailable. */ }
}

export function restoreLanguageDraft() {
  const form = document.querySelector('#gift-form');
  if (!form) return;
  try {
    const stored = sessionStorage.getItem(draftKey);
    if (!stored) return;
    sessionStorage.removeItem(draftKey);
    const draft = JSON.parse(stored);
    for (const input of form.querySelectorAll('[name="recipient"]')) input.checked = input.value === draft.recipient;
    form.elements.budget.value = String(draft.budget || '').slice(0, 20);
    form.elements.note.value = String(draft.note || '').slice(0, 600);
    if (draft.preview) form.requestSubmit();
  } catch { /* Ignore unavailable storage or an invalid temporary draft. */ }
}
